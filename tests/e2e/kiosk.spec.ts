import { expect, test, type Page } from "@playwright/test";

async function signIn(page: Page, passcode: string) {
  await page.goto("/");
  await page.waitForSelector('body[data-hydrated="true"]');
  await page.getByLabel("Restaurant passcode").fill(passcode);
  await expect(accountButton(page)).toBeVisible({ timeout: 60000 });
}

function accountButton(page: Page) {
  return page
    .getByRole("button", { name: "Account and quick settings" })
    .first();
}

async function openSettings(page: Page) {
  await expect(accountButton(page)).toBeVisible();
  const desktopButton = page.getByRole("button", {
    name: "Settings",
    exact: true,
  });
  if (await desktopButton.isVisible()) {
    await desktopButton.click();
    return;
  }
  const moreButton = page.getByRole("button", { name: "More" });
  if ((await moreButton.getAttribute("aria-expanded")) !== "true") {
    await moreButton.click();
  }
  await page.getByRole("button", { name: /^Settings/ }).click();
}

test.describe("Kiosk Surface and Location Administration (V2-007)", () => {
  test("unpaired tablet navigates to /kiosk and renders full-screen pairing screen", async ({
    page,
  }) => {
    await page.goto("/kiosk");

    // Verify full-screen kiosk surface without main navigation header
    await expect(page.getByTestId("kiosk-pairing-screen")).toBeVisible();
    await expect(
      page.getByRole("heading", { name: /Clock In \/ Out Kiosk/i }),
    ).toBeVisible();
    await expect(
      page.getByText(
        "Enter the 6-character pairing code generated by your manager in",
      ),
    ).toBeVisible();

    // Verify touch-friendly alphanumeric keypad is rendered
    await expect(page.getByTestId("key-2")).toBeVisible();
    await expect(page.getByTestId("key-A")).toBeVisible();
    await expect(page.getByTestId("key-Z")).toBeVisible();
    await expect(page.getByTestId("key-backspace")).toBeVisible();
    await expect(page.getByTestId("key-clear")).toBeVisible();

    // Tap keys and verify character slot input
    await page.getByTestId("key-A").click();
    await page.getByTestId("key-B").click();
    await page.getByTestId("key-C").click();
    await expect(page.getByTestId("code-box-0")).toHaveText("A");
    await expect(page.getByTestId("code-box-1")).toHaveText("B");
    await expect(page.getByTestId("code-box-2")).toHaveText("C");

    // Test backspace
    await page.getByTestId("key-backspace").click();
    await expect(page.getByTestId("code-box-2")).toHaveText("");

    // Test clear
    await page.getByTestId("key-clear").click();
    await expect(page.getByTestId("code-box-0")).toHaveText("");
    await expect(page.getByTestId("code-box-1")).toHaveText("");
  });

  test("manager navigates to Location Administration and views Kiosks management tab", async ({
    page,
  }) => {
    // Sign in as manager
    await signIn(page, "2468");
    await openSettings(page);

    // Open Locations card in Settings
    const locationsCard = page.locator("#settings-locations");
    await expect(locationsCard).toBeVisible();
    await locationsCard.click();

    // Select the first location (Webster Branch)
    const manageWebster = page.getByRole("button", {
      name: "Manage Webster Branch",
    });
    await expect(manageWebster).toBeVisible();
    await manageWebster.click();

    await expect(
      page.getByRole("heading", { name: "Manage Webster Branch" }),
    ).toBeVisible();

    // Switch to Kiosks tab
    const kiosksButton = page.getByRole("button", { name: "Kiosks" });
    await expect(kiosksButton).toBeVisible();
    await kiosksButton.click();

    // Verify Kiosks management panel content
    await expect(
      page.getByRole("heading", { name: "Station Kiosk Tablets" }),
    ).toBeVisible();
    await expect(
      page.getByText(/Manage physical tablets paired to/i),
    ).toBeVisible();

    // Verify "Add Kiosk Device" button
    const addDeviceButton = page.getByRole("button", {
      name: "Add Kiosk Device",
    });
    await expect(addDeviceButton.first()).toBeVisible();
  });
});
