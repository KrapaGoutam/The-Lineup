// Generates supabase/tests/database/0034_bar_inventory_key_vectors.test.sql from
// tests/fixtures/bar-inventory/keys-vectors.json so the SQL key functions and
// the TypeScript mirror are proven against ONE source of truth.
//
//   node scripts/bar-inventory/generate-pgtap-vectors.mjs
//
// generate-pgtap-vectors.test.ts fails when the committed SQL drifts from the
// JSON (run the command above and commit the result).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
export const VECTORS_PATH = path.join(
  root,
  "tests/fixtures/bar-inventory/keys-vectors.json",
);
export const OUTPUT_PATH = path.join(
  root,
  "supabase/tests/database/0034_bar_inventory_key_vectors.test.sql",
);

/** Dollar-quoted literal; vectors never contain the `$kv$` tag. */
function lit(value) {
  if (value === null || value === undefined) return "null";
  if (String(value).includes("$kv$")) throw new Error("vector contains $kv$");
  return `$kv$${value}$kv$`;
}

function label(text) {
  return lit(text);
}

export function generateKeyVectorTest(keys) {
  const cases = [];
  const add = (sql, description) => cases.push({ sql, description });

  for (const v of keys.nameKey) {
    add(
      `select is(private.inventory_name_key(${lit(v.input)}), ${lit(v.expected)}::text, ${label(`nameKey(${JSON.stringify(v.input)}) -> ${v.expected}`)});`,
    );
  }
  keys.sameVendor.forEach((group, i) => {
    const array = `array[${group.map(lit).join(", ")}]::text[]`;
    add(
      `select is((select count(distinct private.inventory_name_key(v))::int from unnest(${array}) as v), 1, ${label(`sameVendor group ${i + 1} collapses to one key`)});`,
    );
  });
  for (const v of keys.sizeKey) {
    add(
      `select is(private.inventory_size_key(${lit(v.input)}), ${lit(v.expected)}::text, ${label(`sizeKey(${JSON.stringify(v.input)}) -> ${JSON.stringify(v.expected)}`)});`,
    );
  }
  for (const v of keys.skuKey) {
    add(
      `select is(private.inventory_sku_key(${lit(v.input)}), ${lit(v.expected)}::text, ${label(`skuKey(${JSON.stringify(v.input)}) -> ${v.expected}`)});`,
    );
  }
  for (const v of keys.unitKey) {
    add(
      `select is(private.inventory_unit_key(${lit(v.type)}, ${lit(v.label)}), ${lit(v.expected)}::text, ${label(`unitKey(${v.type}, ${JSON.stringify(v.label)}) -> ${v.expected}`)});`,
    );
  }

  const identity = (p) =>
    `(private.inventory_name_key(${lit(p.vendor)}) || '|' || private.inventory_name_key(${lit(p.name)}) || '|' || private.inventory_size_key(${lit(p.size)}) || '|' || private.inventory_unit_key(${lit(p.unit)}, null))`;
  keys.identity.same.forEach(([a, b], i) => {
    add(
      `select is(${identity(a)}, ${identity(b)}, ${label(`identity same #${i + 1}`)});`,
    );
  });
  keys.identity.different.forEach(([a, b], i) => {
    add(
      `select isnt(${identity(a)}, ${identity(b)}, ${label(`identity different #${i + 1}`)});`,
    );
  });

  return [
    "-- GENERATED by scripts/bar-inventory/generate-pgtap-vectors.mjs from",
    "-- tests/fixtures/bar-inventory/keys-vectors.json. Do not edit by hand:",
    "-- change the JSON and re-run the generator.",
    "begin;",
    "",
    "create extension if not exists pgtap with schema extensions;",
    "",
    `select plan(${cases.length});`,
    "",
    ...cases.map((c) => c.sql),
    "",
    "select * from finish();",
    "rollback;",
    "",
  ].join("\n");
}

export const STATUS_VECTORS_PATH = path.join(
  root,
  "tests/fixtures/bar-inventory/status-vectors.json",
);
export const STATUS_OUTPUT_PATH = path.join(
  root,
  "supabase/tests/database/0036_bar_inventory_status_vectors.test.sql",
);

const num = (value) => (value === null ? "null::numeric" : `${value}::numeric`);

/**
 * One product + stock row per vector, asserted THROUGH the real
 * inventory_stock_status view (generated total, warning fallback, status,
 * suggested order, "order needed", archived exclusion).
 */
export function generateStatusVectorTest(status) {
  const ID = "00000000-0000-0000-0000-0000000360";
  const org = `${ID}11`;
  const loc = `${ID}21`;
  const user = `${ID}01`;
  const vendor = `${ID}31`;
  const vectors = status.vectors;
  const lines = [
    "-- GENERATED by scripts/bar-inventory/generate-pgtap-vectors.mjs from",
    "-- tests/fixtures/bar-inventory/status-vectors.json. Do not edit by hand:",
    "-- change the JSON and re-run the generator.",
    "begin;",
    "",
    "create extension if not exists pgtap with schema extensions;",
    "",
    `select plan(${vectors.length + 1});`,
    "",
    `insert into auth.users (id, email, encrypted_password, email_confirmed_at, aud, role) values ('${user}', '0361-owner@passcode.internal', 'x', now(), 'authenticated', 'authenticated');`,
    `insert into public.profiles (id, display_name) values ('${user}', 'PGTAP 0361 Owner');`,
    `insert into public.organizations (id, name, slug, created_by) values ('${org}', 'PGTAP 0361 Org', 'pgtap-0361-org', '${user}');`,
    `insert into public.locations (id, organization_id, name, time_zone) values ('${loc}', '${org}', 'PGTAP 0361 Loc', 'America/New_York');`,
    `insert into public.memberships (organization_id, profile_id, roles, active) values ('${org}', '${user}', array['owner']::public.app_role[], true);`,
    `insert into public.inventory_vendors (id, organization_id, name, created_by) values ('${vendor}', '${org}', 'Vector Vendor', '${user}');`,
    "",
  ];
  vectors.forEach((v, i) => {
    const pid = `00000000-0000-0000-0000-00000036${String(1000 + i).padStart(4, "0")}`;
    const active = !v.input.archived;
    lines.push(
      `insert into public.inventory_products (id, organization_id, vendor_id, name, unit_type, active, archived_at, created_by) values ('${pid}', '${org}', '${vendor}', ${lit(`vector ${v.id}`)}, 'bottle', ${active}, ${active ? "null" : "now()"}, '${user}');`,
      `update public.inventory_stock set on_hand = ${v.input.on_hand}, backup = ${v.input.backup}, cutoff = ${v.input.cutoff ?? "null"}, warning = ${v.input.warning ?? "null"}, par = ${v.input.par ?? "null"} where product_id = '${pid}' and location_id = '${loc}';`,
    );
  });
  lines.push("");
  vectors.forEach((v, i) => {
    const pid = `00000000-0000-0000-0000-00000036${String(1000 + i).padStart(4, "0")}`;
    const e = v.expected;
    lines.push(
      `select results_eq($q$select total::numeric, effective_warning::numeric, status, suggested_order::numeric, order_needed from public.inventory_stock_status where product_id = '${pid}' and location_id = '${loc}'$q$, $q$values (${num(e.total)}, ${num(e.effective_warning)}, ${lit(e.status)}::text, ${num(e.suggested_order)}, ${e.order_needed})$q$, ${label(`status vector ${v.id}`)});`,
    );
  });
  lines.push(
    `select is((select count(*)::int from public.inventory_stock_status where location_id = '${loc}'), ${vectors.length}, 'the view exposes exactly one row per vector');`,
    "",
    "select * from finish();",
    "rollback;",
    "",
  );
  return lines.join("\n");
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const keys = JSON.parse(readFileSync(VECTORS_PATH, "utf8"));
  writeFileSync(OUTPUT_PATH, generateKeyVectorTest(keys), "utf8");
  console.log(`wrote ${path.relative(root, OUTPUT_PATH)}`);
  const status = JSON.parse(readFileSync(STATUS_VECTORS_PATH, "utf8"));
  writeFileSync(STATUS_OUTPUT_PATH, generateStatusVectorTest(status), "utf8");
  console.log(`wrote ${path.relative(root, STATUS_OUTPUT_PATH)}`);
}
