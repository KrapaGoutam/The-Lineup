-- Feature 027. Recurring shift generation needs a way to group the
-- individual `shifts` rows one "repeat on Tue/Thu from X to Y"
-- submission produces, so a future feature (bulk-edit/bulk-delete a
-- whole series) has something to key on -- not used for that yet, just
-- carried through from creation.
--
-- Correction, found reading the schema directly rather than assumed:
-- `shifts.series_id uuid` already exists, added by
-- 20260905125418_operational_modules.sql, and is completely unused by
-- any application code (grep confirms it appears nowhere outside the
-- generated types). This is exactly the column the spec's
-- `recurrence_group_id` describes -- adding a second, redundantly-named
-- uuid column for the identical purpose would leave two overlapping
-- concepts on the same table. `series_id` is reused as-is (nullable --
-- a plain, single-date shift has no series at all, not a
-- self-referential series of one) rather than renamed, since renaming
-- an existing column is a strictly riskier migration than not touching
-- it, for zero behavioral gain.
--
-- `is_recurring` is genuinely new -- nothing already distinguishes "was
-- deliberately created as part of a repeat-on-weekdays batch" from
-- "happens to share a series_id for some other future reason." Kept
-- separate from `series_id is not null` so the two questions ("is this
-- part of a series" and "was this generated by the recurring-days
-- feature specifically") don't have to stay silently in sync forever.
--
-- No RLS change needed here -- confirmed by reading
-- 20260905065702_initial_schema.sql directly: `shifts` already has a
-- permissive `shifts_write_manager` policy (`for all`, no draft/
-- published distinction) covering insert/update/delete for owner/
-- general_manager/shift_manager, and `shifts_select_member`/
-- `shifts_published_or_manager` already cover every read. A new column
-- falls under both existing policies automatically -- it is not a new
-- grant.
alter table public.shifts
  add column is_recurring boolean not null default false;
